"""Builds the Phase 7 customer profitability report. All numbers are read from computed results."""
from __future__ import annotations

import pandas as pd

from .customer_analysis import MIN_ORDERS, SEGMENTS
from .findings import _tbl, money, pct
from .reporting import md_table

EX_COLS = ["customer_id", "customer_name", "segment", "revenue", "profit", "profit_margin", "orders",
           "effective_discount", "beyond_be_share"]
EX_FMT = {"revenue": "money", "profit": "money", "profit_margin": "pct", "orders": "int",
          "effective_discount": "pct", "beyond_be_share": "pct"}

MEANING = {
    "C1": ("The accounts that carry the business: above-median revenue at margins above the company average, bought mostly at or near list price. "
           "They are the profit base and the main concentration risk."),
    "C2": ("Customers who buy a lot but earn the company little or nothing as a group. Their revenue is concentrated in lines sold beyond the "
           "product's break-even discount; on their other lines they are profitable."),
    "C3": ("Smaller customers who are efficient: they buy little, but at good margins and modest discounts. Their absolute profit contribution is limited "
           "by their size."),
    "C4": ("Small customers whose purchases fall heavily in deeply discounted lines. Small revenue, net losses as a group."),
}
LIMITS = {
    "C1": "Membership is based on four years of history and is not stable over time (section 7); the label describes the past, not a customer type.",
    "C2": "Low margin reflects which state and sub-category rules their orders fell under; the data does not show the customer asking for or negotiating discounts.",
    "C3": "There is no evidence on whether these customers could buy more; small revenue per customer limits the reliability of individual margins.",
    "C4": "Many have only 3-6 orders; one deeply discounted line can decide their classification.",
}


def build_report(r: dict, figs: dict[str, str], validation: pd.DataFrame) -> str:
    c, s, cm, cov, per = r["customers"], r["segments"], r["company_margin"], r["coverage"], r["persistence"]
    sc, ud, ig = r["seg_comparison"].set_index("segmentation"), r["unprofitable"].set_index("group"), r["investigation"]
    L: list[str] = []
    add = L.append

    add("# Phase 7 — Customer Profitability Analysis")
    add("**Business question:** Which customers create profit, which dilute it, and which customer groups deserve further commercial investigation?  ")
    add(f"**Population:** {len(c)} valid customers (core scope; placeholder and identity-anomaly customers excluded). "
        f"Revenue {money(c['revenue'].sum())}, profit {money(c['profit'].sum())}, margin {pct(cm)}.  ")
    add(f"**Validation:** {(validation.status == 'PASS').sum()}/{len(validation)} checks passed.  ")
    add("_Generated by `scripts/run_phase7_customers.py`; all figures are computed at run time._\n")

    # ---------------- 1 ----------------
    c1, c2 = s.loc["C1"], s.loc["C2"]
    add("## 1. Executive summary")
    add(f"- **Profit is concentrated.** Core accounts (C1) are {pct(c1['share_of_customers'],0)} of customers, {pct(c1['share_of_revenue'],0)} of revenue "
        f"and {pct(c1['share_of_profit'],0)} of profit. The top 10% of customers by profit generate {pct(r['top10_profit_share'],0)} of all customer profit.")
    add(f"- **A large block of revenue earns nothing.** Margin-dilutive accounts (C2) are {pct(c2['share_of_customers'],0)} of customers and "
        f"{pct(c2['share_of_revenue'],0)} of revenue, but lose {money(-c2['profit'])} as a group.")
    add(f"- **Customer losses trace back to specific lines.** All {int(ud.loc['Unprofitable customers','customers'])} unprofitable customers bought at least one "
        f"line beyond break-even; {int(ud.loc['... profitable on their within-break-even lines','customers'])} of them are profitable on their remaining lines.")
    add(f"- **Customer profitability is not a stable trait in this data.** A customer's margin in {per['period_1']} has no relationship with their margin in "
        f"{per['period_2']} (rho = {per['spearman_margin']:.2f}); only {pct(per['same_segment_share'],0)} of customers stay in the same segment.")
    add("- **Implication:** commercial investigation should focus on the transactions and discount rules behind weak customer profit, and on protecting "
        "core accounts. It should not label individual customers as 'bad customers'.\n")

    # ---------------- 2 ----------------
    add("## 2. Population and what the data can say about customer history")
    add(f"- {pct(cov['share_first_seen_in_first_year'],0)} of customers are first seen in the first data year, so most customer histories are **left-censored**: "
        "we cannot tell whether they are new or long-standing.")
    add(f"- {pct(cov['share_active_in_last_year'],0)} ordered in the final year, so recency barely separates customers.")
    add(f"- {pct(cov['share_with_fewer_than_3_orders'],1)} of customers have fewer than {MIN_ORDERS} orders and are not classified ('limited history').")
    add("- **Supported:** revenue, profit, orders, AOV, observed tenure, days between orders, days since last order, active years.")
    add("- **Not supported:** true customer lifetime value, acquisition date or cost, churn (no definition of a lost customer), and any customer-level cost to serve.\n")

    # ---------------- 3 ----------------
    add("## 3. Customer metrics")
    add("Distributions are skewed, so medians are the representative figure; means are shown for reference.\n")
    h = r["headline"].copy().astype(object)
    for idx in h.index:
        fmt = (lambda v: f"{v:.1%}") if "margin" in idx else (lambda v: f"{v:,.1f}") if r["headline"].loc[idx, "90%"] < 20 else (lambda v: f"{v:,.0f}")
        h.loc[idx] = [fmt(float(v)) for v in r["headline"].loc[idx]]
    add(md_table(h.reset_index().rename(columns={"index": "metric"})))
    add(f"\n![history]({figs['K6']})\n")
    add(f"Company-level reference: AOV {money(c['revenue'].sum() / c['orders'].sum())}, revenue per customer {money(c['revenue'].mean())}, "
        f"profit per customer {money(c['profit'].mean())}, orders per customer {c['orders'].mean():.1f}.\n")

    # ---------------- 4 ----------------
    add("## 4. Choosing the segmentation")
    add("Candidate approaches were compared by how much of the variation in customer **margin** and customer **profit** lies between their groups "
        "(eta-squared). A useful profitability segmentation must separate customers who earn money from those who do not.\n")
    add(_tbl(r["seg_comparison"], ["segmentation", "groups", "eta_margin", "eta_profit"],
             {"groups": "int", "eta_margin": "pct", "eta_profit": "pct"}, index=False))
    add(f"\n![segmentation]({figs['K4']})\n")
    add("**Why RFM is not used as the primary segmentation:**")
    add(f"- Recency and frequency tell us almost nothing about customer margin (R: {pct(sc.loc['Recency quintile (R)','eta_margin'],1)}, "
        f"F: {pct(sc.loc['Frequency quintile (F)','eta_margin'],1)}).")
    add(f"- RFM ranks customers by revenue (monetary), not profit, so it cannot distinguish a high-revenue profitable customer from a high-revenue loss-making one.")
    add(f"- The full RFM score needs {int(sc.loc['Full RFM score','groups'])} groups to reach {pct(sc.loc['Full RFM score','eta_margin'],0)}, "
        f"whereas a four-group revenue x margin matrix reaches {pct(sc.loc['Revenue x margin matrix (this analysis)','eta_margin'],0)}.")
    add("- RFM was designed to predict response to marketing contact; this question is about profitability.\n")
    add("**Chosen approach: revenue x margin matrix**")
    add("| Element | Definition | Why |")
    add("|---|---|---|")
    add(f"| Evidence rule | At least {MIN_ORDERS} orders | Avoids classifying customers on one or two transactions |")
    add(f"| Revenue axis | Revenue >= median of eligible customers ({money(r['revenue_cut'])}) | Robust to the skewed revenue distribution |")
    add(f"| Profit axis | Margin >= company margin ({pct(cm)}) | Absolute profit largely mirrors revenue; margin measures profit quality independent of size. "
        "'Low revenue, high profit' only makes sense as high margin |")
    add("\nThe matrix is identical in logic to the product framework (Phase 5), so products and customers are judged by the same rules.\n")

    # ---------------- 5 ----------------
    add("## 5. Segment results")
    add(f"![matrix]({figs['K1']})\n")
    add(_tbl(s, ["customers", "share_of_customers", "revenue", "share_of_revenue", "profit", "share_of_profit", "profit_margin",
                 "effective_discount", "beyond_be_share", "unprofitable"],
             {"customers": "int", "share_of_customers": "pct", "revenue": "money", "share_of_revenue": "pct", "profit": "money",
              "share_of_profit": "pct", "profit_margin": "pct", "effective_discount": "pct", "beyond_be_share": "pct", "unprofitable": "int"}))
    add("\n**Per-customer view (medians and averages)**\n")
    add(_tbl(s, ["median_revenue", "median_profit", "median_orders", "median_aov", "revenue_per_customer", "profit_per_customer", "orders_per_customer"],
             {"median_revenue": "money", "median_profit": "money", "median_orders": "num", "median_aov": "money",
              "revenue_per_customer": "money", "profit_per_customer": "money", "orders_per_customer": "num"}))
    add(f"\n![shares]({figs['K2']})\n")
    for seg in ["C1", "C2", "C3", "C4"]:
        row = s.loc[seg]
        add(f"### {seg} — {SEGMENTS[seg]}")
        add(f"**Metrics.** {int(row['customers'])} customers, revenue {money(row['revenue'])} ({pct(row['share_of_revenue'])}), profit {money(row['profit'])} "
            f"({pct(row['share_of_profit'])}), margin {pct(row['profit_margin'])}, effective discount {pct(row['effective_discount'])}, "
            f"{pct(row['beyond_be_share'])} of revenue beyond break-even, {int(row['unprofitable'])} unprofitable customers. "
            f"Median customer: revenue {money(row['median_revenue'])}, profit {money(row['median_profit'])}, {row['median_orders']:.0f} orders.\n")
        add("**Examples** (ranked by absolute profit impact, |profit|):\n")
        add(_tbl(r["examples"][seg], EX_COLS, EX_FMT, index=False))
        add(f"\n**What it means.** {MEANING[seg]}\n")
        add(f"**Limitations.** {LIMITS[seg]}\n")
    na = s.loc["NA"]
    add(f"### Limited history (< {MIN_ORDERS} orders)")
    add(f"{int(na['customers'])} customers, {pct(na['share_of_revenue'])} of revenue. Not classified; monitored separately.\n")
    add("### Robustness")
    add(_tbl(r["sensitivity"], ["scenario", "reclassified", "share_reclassified", "c2_customers", "c2_profit"],
             {"reclassified": "int", "share_reclassified": "pct", "c2_customers": "int", "c2_profit": "money"}, index=False))
    add(f"\nShifting either threshold reclassifies 7-10% of customers, but the margin-dilutive segment loses money in every scenario. "
        "The pattern does not depend on the exact cut-offs.\n")

    # ---------------- 6 ----------------
    add("## 6. Why are some customers low-margin?")
    add(f"![decomposition]({figs['K3']})\n")
    add(f"Each customer's profit is split into lines sold within the product's break-even discount and lines sold beyond it (Phase 6). "
        f"Every segment is profitable on its within-break-even lines. C2's net loss comes from {pct(c2['beyond_be_share'],0)} of its revenue sold beyond "
        f"break-even, which loses {money(-c2['beyond_be_profit'])}.\n")
    add(md_table(r["unprofitable"], floatfmt=lambda v: f"{v:,.0f}"))
    add("\n**What the data shows about discounts and customers.** Discount is fixed by state x sub-category (Phase 4), so every customer receives the same "
        "discount as any other customer buying the same sub-category in the same state. Differences in customer discount therefore reflect where they ship "
        "and what they buy, not a customer-specific deal. The data contains no evidence of customers negotiating discounts.\n")

    # ---------------- 7 ----------------
    add("## 7. Is customer profitability a stable customer trait?")
    add(f"Customers active in both {per['period_1']} and {per['period_2']} ({per['customers_in_both']}) were classified separately in each period.\n")
    add(f"![persistence]({figs['K5']})\n")
    add("| Measure | Value |")
    add("|---|---|")
    add(f"| Rank correlation of margin, period 1 vs period 2 | {per['spearman_margin']:.2f} |")
    add(f"| Rank correlation of revenue | {per['spearman_revenue']:.2f} |")
    add(f"| Rank correlation of profit | {per['spearman_profit']:.2f} |")
    add(f"| Low-margin in period 2, if low-margin in period 1 | {pct(per['p_low_margin_again_if_low'],0)} |")
    add(f"| Low-margin in period 2, if high-margin in period 1 | {pct(per['p_low_margin_if_previously_high'],0)} |")
    add(f"| Same segment in both periods | {pct(per['same_segment_share'],0)} (about 25% expected by chance) |")
    add("\n**Reading.** Past profitability does not predict future profitability at customer level: being low-margin in the first period barely changes the "
        "chance of being low-margin in the second. Segment membership describes the past four years, not a lasting customer type. This is a strong reason not to "
        "act on individual customers (for example, by dropping them) on the basis of these segments.\n")
    add("**Limitation.** The synthetic dataset may assign orders to customers with little real-world structure, which would also produce this result. In a real "
        "business, this test should be repeated before any customer-level action.\n")

    # ---------------- 8 ----------------
    add("## 8. Business segment composition")
    add(_tbl(r["by_type"], list(r["by_type"].columns), {k: "pct" for k in r["by_type"].columns}))
    add("\nConsumer, Corporate and Home Office customers are spread similarly across the profitability segments; business segment is not a useful "
        "predictor of customer profitability (consistent with Phase 4).\n")

    # ---------------- 9 ----------------
    add("## 9. Which customer groups deserve further commercial investigation?")
    add("**Metrics used:** *loss* = sum of negative customer profit in the group; *hurdle shortfall* = revenue x (company margin - customer margin), summed over "
        "customers below the company margin: the profit the group would add if it earned the company-average margin. Neither is a forecast.\n")
    add(_tbl(ig, ["group", "customers", "revenue", "profit", "loss", "hurdle_shortfall", "beyond_be_share", "share_of_total_profit"],
             {"customers": "int", "revenue": "money", "profit": "money", "loss": "money", "hurdle_shortfall": "money",
              "beyond_be_share": "pct", "share_of_total_profit": "pct"}, index=False))
    g = ig.set_index("group")
    l2, p2 = g.loc["C2 customers that are loss-making"], g.loc["C2 customers that are profitable but below hurdle"]
    add("\n**Recommended investigation priorities**\n")
    add(f"1. **Loss-making high-revenue customers (C2, {int(l2['customers'])} customers).** Largest loss ({money(-l2['loss'])}) and hurdle shortfall "
        f"({money(l2['hurdle_shortfall'])}); {pct(l2['beyond_be_share'],0)} of their revenue is beyond break-even. *Investigate:* which orders, states and "
        "sub-category rules produced the losses, and whether any were approved exceptions. The action is on the rules and approvals, not the customers.")
    add(f"2. **Core accounts (C1) and the top 10% by profit.** {pct(g.loc['C1 core accounts (concentration risk)','share_of_total_profit'],0)} of customer profit "
        f"comes from C1; the top 10% alone generate {pct(g.loc['Top 10% of customers by profit','share_of_total_profit'],0)}. *Investigate:* account coverage, "
        "service levels and what share of each account's needs the company serves. No evidence here says they are at risk; the point is dependence.")
    add(f"3. **Profitable but below-hurdle C2 customers ({int(p2['customers'])}).** Profitable ({money(p2['profit'])}) yet {money(p2['hurdle_shortfall'])} below "
        "the company-average margin. *Investigate:* the mix of deeply discounted lines in their orders; these are the accounts where tighter discount guardrails "
        "would matter most.")
    add(f"4. **Low-value accounts (C4).** Small revenue; loss-making customers in this group lose {money(-g.loc['C4 low-value accounts','loss'])}. *Investigate:* whether cost to serve "
        "(not in the data) makes small, deeply discounted orders uneconomic.")
    add(f"5. **Limited-history customers ({int(g.loc['Limited-history customers','customers'])}).** Too few orders to judge. *Monitor* rather than act.\n")
    add("## 10. What this analysis does not claim")
    add("- That any customer *behaves* in a particular way (negotiates, cherry-picks, is loyal or at risk): the data records transactions, not intentions.")
    add("- That segments are stable: section 7 shows they are not.")
    add("- Customer lifetime value, churn or acquisition: history is left-censored and costs are absent.")
    add("- That dropping or repricing customers would raise profit: volume responses are unknown (Phase 6).\n")
    add("## 11. Validation")
    add(md_table(validation, floatfmt=lambda v: f"{v:,.2f}"))
    return "\n".join(L)
