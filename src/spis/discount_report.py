"""Builds the Phase 6 discount report. Every number is read from computed results."""
from __future__ import annotations

import pandas as pd

from .discount_analysis import RECOMMENDED_SCHEME
from .findings import _tbl, money, pct
from .reporting import md_table

TAG = {"D": "**[Descriptive]**", "C": "**[Correlation]**", "E": "**[Explanation]**", "X": "**[Causal]**"}

DIM_COLS = ["sales", "profit", "profit_margin", "effective_discount", "avg_line_discount", "share_lines_discounted",
            "share_lines_deep", "list_margin", "share_sales_beyond_break_even"]
DIM_FMT = {"sales": "money", "profit": "money", "profit_margin": "pct", "effective_discount": "pct",
           "avg_line_discount": "pct", "share_lines_discounted": "pct", "share_lines_deep": "pct",
           "list_margin": "pct", "share_sales_beyond_break_even": "pct"}


def growth_sentence(gsum: pd.DataFrame) -> str:
    o = gsum.filter(like="orders_index").iloc[:, 0]
    u = gsum.filter(like="units_index").iloc[:, 0]
    disc_o, disc_u = o.drop("0%"), u.drop("0%")
    return (f"Order growth over the period was {o['0%']:.2f}x at full price and {disc_o.min():.2f}-{disc_o.max():.2f}x in the discounted bands; "
            f"unit growth was {u['0%']:.2f}x vs {disc_u.min():.2f}-{disc_u.max():.2f}x. There is no consistent pattern of faster growth where discounts are deeper.")


def build_report(r: dict, figs: dict[str, str], validation: pd.DataFrame) -> str:
    o, av, lv, hd, ic, rs = r["overall"], r["averages"], r["levels"], r["headroom"], r["identity"], r["rule_stability"]
    corr, gsum, bev, bands = r["correlations"].set_index(["relationship", "level"]), r["growth"]["summary"], r["band_eval"], r["band_details"]
    eff = av.set_index("measure")["value"]
    L: list[str] = []
    add = L.append

    add("# Phase 6 — Discount and Profitability Analysis")
    add("**Business question:** Is discounting helping the business generate profitable growth, or is it eroding profitability?  ")
    add(f"**Scope:** core scope (US, suspected copies excluded): revenue {money(o['sales'])}, profit {money(o['profit'])}, "
        f"{int(o['lines']):,} order lines.  ")
    add(f"**Validation:** {(validation.status == 'PASS').sum()}/{len(validation)} checks passed.  ")
    add("_Generated by `scripts/run_phase6_discount.py`; all figures are computed at run time._\n")
    add("## How claims are labelled")
    add("| Label | Meaning | What it can support |")
    add("|---|---|---|")
    add("| [Descriptive] | What the numbers are | 'Deep-discount lines lose money' |")
    add("| [Correlation] | How strongly two variables move together (Spearman rank correlation) | 'Higher discount goes with lower margin' |")
    add("| [Explanation] | A mechanism verified in the data, or a plausible business reason | 'Margin falls because price falls while unit cost stays fixed' |")
    add("| [Causal] | What would happen if discount were changed | Only claims the data's variation can actually support (see section 9) |\n")

    # ---------------- 1. Answer ----------------
    hb = hd.loc["Discounted beyond break-even"]
    safe = hd.loc["Discounted, >10 pp below break-even"]
    add("## 1. Short answer")
    add(f"- {TAG['D']} The business gave away {money(o['discount_amount'])} of list value through discounts, about "
        f"{o['discount_amount'] / o['profit']:.1f}x its total profit ({money(o['profit'])}).")
    add(f"- {TAG['D']} Moderate discounting is still profitable: discounted lines more than 10 points below their product's break-even "
        f"earn {money(safe['profit'])} at {pct(safe['profit_margin'])} margin. Discounting **beyond** break-even "
        f"({pct(hb['share_of_sales'])} of revenue) loses {money(-hb['profit'])}, which is all of the line-level losses in the business.")
    add(f"- {TAG['E']} The mechanism is verified price arithmetic: each product has a fixed unit cost, so a discount lowers its margin by an exactly "
        f"predictable amount. Verified: the implied list margin is constant within every product, and predicts the margin of every "
        f"discounted line exactly. It follows that a line loses money when its discount exceeds the product's list margin.")
    add(f"- {TAG['C']} There is no sign that discounting buys volume or growth: discount vs units per line "
        f"rho = {abs(corr.loc[('Discount vs units per line','Order line'),'spearman_rho']):.2f}; discount vs state revenue growth "
        f"rho = {corr.loc[('Effective discount vs revenue growth 2023-2026','State (30+ orders)'),'spearman_rho']:.2f}. "
        f"{growth_sentence(gsum)}")
    add(f"- {TAG['X']} A causal estimate of what would happen to **total** profit and volume if discounts changed is **not possible** from this data: "
        f"discount never varies within a state x sub-category rule ({rs['cells_with_more_than_one_discount_level']} of {rs['policy_cells']} rules vary) "
        f"and no rule changed over four years ({rs['multi_year_cells_where_rule_changed']} of {rs['cells_observed_in_several_years']}).")
    add("- **Management reading:** discounting as currently applied is not visibly generating profitable growth. The part beyond break-even erodes "
        "profit on every unit sold. Whether removing it would also lose sales is unknown and should be tested with a controlled pilot.\n")

    # ---------------- 2. Average discount ----------------
    add("## 2. What is the 'average discount'?")
    add(f"{TAG['D']} The answer depends on the definition, so all are shown. The effective discount rate is used throughout this report "
        "because it answers the business question 'what share of list value did we give up?'\n")
    add(md_table(av.assign(value=av["value"].map(lambda v: pct(v)))))
    add("")

    # ---------------- 3. Distribution ----------------
    dist = r["distribution"]
    add("## 3. Discount distribution")
    add(f"{TAG['D']} Discount takes only {len(dist)} distinct values. {pct(dist.loc[0.0,'share_of_lines'])} of lines are at full price and "
        f"{pct(dist.loc[0.2,'share_of_lines'])} at exactly 20%. Lines at 30% or more are {pct(eff['Share of lines at 30%+ discount'])} of lines "
        f"but account for {pct(dist.loc[dist.index >= 0.3, 'share_of_discount_given'].sum())} of all discount given away.\n")
    add(f"![distribution]({figs['D1']})\n")
    add(_tbl(dist, ["lines", "share_of_lines", "sales", "share_of_sales", "discount_amount", "share_of_discount_given"],
             {"lines": "int", "share_of_lines": "pct", "sales": "money", "share_of_sales": "pct",
              "discount_amount": "money", "share_of_discount_given": "pct"}))
    add("")

    # ---------------- 4. Bands ----------------
    add("## 4. Are the proposed discount bands appropriate?")
    add("The proposed bands (0%, 1-10%, 10-20%, 20-30%, 30%+) were evaluated against two alternatives and the 12 raw levels using four stated criteria: "
        "explanatory power (share of the margin detail in the 12 raw levels that the bands retain), smallest band size, "
        "homogeneity (largest margin range between levels grouped into one band), and whether a boundary sits at the profit break-even (20% to 30%).\n")
    add(_tbl(bev, ["scheme", "bands", "eta_squared", "share_of_level_detail_retained", "smallest_band_lines",
                   "max_margin_range_within_band", "boundary_at_break_even_20_30"],
             {"bands": "int", "eta_squared": "pct", "share_of_level_detail_retained": "pct", "smallest_band_lines": "int",
              "max_margin_range_within_band": "pct"}, index=False))
    a = bands["A. Proposed: 0 | 1-10 | 10-20 | 20-30 | 30+"]
    b = bands[RECOMMENDED_SCHEME]
    add(f"\n**Problems with the proposed bands, specific to this dataset:**")
    add("- The boundaries overlap as written (is 10% in '1-10%' or '10-20%'?). They were implemented as (0,10], (10,20], (20,30], >30.")
    add(f"- '1-10%' contains a single discount level (10%) with {int(a.loc['1-10%','lines'])} lines, and '20-30%' contains only 30%.")
    add(f"- '30%+' groups {int(a.loc['30%+','levels_in_band'])} levels whose margins range over {pct(a.loc['30%+','margin_range_within_band'],0)} "
        f"(from {pct(lv.loc[0.3,'profit_margin'])} at 30% to {pct(lv.loc[0.8,'profit_margin'])} at 80%), hiding the difference between moderate and extreme discounting.\n")
    add(f"**Decision:** keep the model bands (0 | 1-20 | 21-40 | 41-60 | 61-80). They retain "
        f"{pct(bev.set_index('scheme').loc[RECOMMENDED_SCHEME,'share_of_level_detail_retained'],0)} of the raw-level detail with every band above "
        f"{int(b['lines'].min())} lines, they match the bands already used in SQL and Power BI, and the 20% boundary sits exactly at the break-even transition. "
        "Alternative C scores marginally higher but creates a 77-line band, which is too thin for stable reporting.\n")
    add(_tbl(b, ["levels_in_band", "lines", "sales", "share_of_sales", "profit", "profit_margin", "margin_range_within_band"],
             {"levels_in_band": "int", "lines": "int", "sales": "money", "share_of_sales": "pct", "profit": "money",
              "profit_margin": "pct", "margin_range_within_band": "pct"}))
    add("\n**A more meaningful band for decisions:** because each product breaks even at its own list margin (section 8), the most useful "
        "grouping for management is distance from break-even rather than the raw discount rate:\n")
    add(_tbl(hd, ["lines", "sales", "share_of_sales", "profit", "share_of_profit", "profit_margin", "loss_line_share"],
             {"lines": "int", "sales": "money", "share_of_sales": "pct", "profit": "money", "share_of_profit": "pct",
              "profit_margin": "pct", "loss_line_share": "pct"}))
    add("")

    # ---------------- 5. By dimension ----------------
    add("## 5. Where is discount applied?")
    add(f"{TAG['D']} 'List margin' is the sales-weighted margin the products would earn at full price, which is also their break-even discount. "
        "'Beyond break-even' is the share of revenue sold at a discount larger than the product's own list margin.\n")
    for key, title in [("dim_category", "Category"), ("dim_sub_category", "Sub-category"), ("dim_region", "Region"), ("dim_segment", "Customer segment")]:
        add(f"### {title}")
        add(_tbl(r[key], DIM_COLS, DIM_FMT))
        add("")
        if key == "dim_sub_category":
            add(f"![sub-category]({figs['D3']})\n")
    sub, reg, seg = r["dim_sub_category"], r["dim_region"], r["dim_segment"]
    add(f"**Reading.** {TAG['D']} Categories receive almost identical effective discounts "
        f"({pct(r['dim_category']['effective_discount'].min())}-{pct(r['dim_category']['effective_discount'].max())}), but sub-categories differ widely "
        f"(from {pct(sub['effective_discount'].min())} to {pct(sub['effective_discount'].max())}). What matters is the discount *relative to list margin*: "
        f"Tables have a list margin of only {pct(sub.loc['Tables','list_margin'])} yet an effective discount of {pct(sub.loc['Tables','effective_discount'])}, "
        f"so {pct(sub.loc['Tables','share_sales_beyond_break_even'],0)} of Tables revenue is sold beyond break-even. Binders and Machines carry high list margins "
        "but receive the deepest discounts. Regions differ sharply "
        f"(Central {pct(reg.loc['Central','effective_discount'])} vs West {pct(reg.loc['West','effective_discount'])}); segments barely differ "
        f"({pct(seg['effective_discount'].min())}-{pct(seg['effective_discount'].max())}).\n")
    add(f"![mix]({figs['D5']})\n")

    # ---------------- 6. Discount -> Sales ----------------
    add("## 6. Discount → Sales")
    add(f"{TAG['D']} Revenue at each discount level mostly reflects how many lines carry that level, not demand. Units per line are the fair comparison: "
        "median line value mainly reflects which products carry each level (10-50% rules apply largely to high-value Machines, Tables and Phones; "
        "60-80% rules mainly to low-priced Binders and Appliances). Units per line barely change with discount:\n")
    add(_tbl(lv, ["lines", "sales", "units_per_line", "median_line_sales", "median_line_list_value"],
             {"lines": "int", "sales": "money", "units_per_line": "num", "median_line_sales": "money", "median_line_list_value": "money"}))
    add(f"\n{TAG['D']} **Growth by band.** Each band is a fixed set of state x sub-category rules (rules never changed), so its growth can be compared:\n")
    add(_tbl(gsum, list(gsum.columns), {c: ("pct" if "cagr" in c else "money" if "profit" in c else "num") for c in gsum.columns}))
    add(f"\n![growth]({figs['D6']})\n")
    add(f"{TAG['C']} Three tests of whether discount is associated with more demand:\n")
    add(_tbl(r["correlations"][r["correlations"]["relationship"].str.contains("units|revenue|growth|purchases")],
             ["relationship", "level", "n", "spearman_rho", "strength"], {"n": "int", "spearman_rho": "num"}, index=False))
    add(f"\n{TAG['E']} **Possible business explanations.** If discounts were winning extra business, we would expect larger baskets on discounted lines, "
        "a larger share of purchases going to sub-categories a state discounts more heavily, or faster growth in high-discount states. None appears. "
        "Possible explanations: discounts are given where customers would have bought anyway; or the rules respond to local competition and only "
        "prevent sales from being lower (which this data cannot show).\n")
    add(f"{TAG['X']} **Causal conclusion:** none. The absence of an association is consistent with discounts not buying volume, but it is not proof, "
        "because discount, location and product are confounded and there is no comparison group.\n")

    # ---------------- 7. Discount -> Profit ----------------
    add("## 7. Discount → Profit")
    add(f"{TAG['D']} Profit by discount band (recommended bands):\n")
    add(_tbl(b, ["lines", "sales", "profit", "profit_margin"], {"lines": "int", "sales": "money", "profit": "money", "profit_margin": "pct"}))
    add(f"\n![levels]({figs['D2']})\n")
    add(f"{TAG['D']} Full-price lines produce {pct(b.loc['0%','profit'] / o['profit'],0)} of total profit; the 1-20% band adds "
        f"{money(b.loc['1-20%','profit'])}; every band above 20% is loss-making in total. Measured by distance from break-even, the "
        f"{pct(hb['share_of_sales'])} of revenue sold beyond break-even loses {money(-hb['profit'])}, while all other discounted revenue earns "
        f"{money(hd.loc[['Discounted, >10 pp below break-even','Discounted, within 10 pp of break-even'],'profit'].sum())}.\n")
    add(f"{TAG['E']} **What a discount would need to deliver** (arithmetic, not observed data). With unit cost fixed, a discount must raise unit volume by "
        "the factor below just to keep profit unchanged:\n")
    add(md_table(r["break_even_volume"].reset_index().assign(discount=lambda t: t["discount"].map(lambda v: pct(v, 0))),
                 floatfmt=lambda v: "not possible" if v == float("inf") else f"{v:.1f}x"))
    lm = r["list_margin_distribution"]
    add(f"\nThe median product has a list margin of {pct(lm['50%'],0)}. A 20% discount on such a product needs about "
        f"{lm['50%'] / (lm['50%'] - 0.2):.1f}x the units to earn the same profit, while section 6 shows discounted lines carry no more units than full-price lines.\n")
    add(f"![volume]({figs['D7']})\n")

    # ---------------- 8. Discount -> Margin ----------------
    add("## 8. Discount → Profit margin")
    add(f"{TAG['D']} Margin falls broadly as discount rises. It is not strictly lower at every step (e.g. 15% vs 20%, 45% vs 50%), "
        "because each discount level applies to a different mix of products with different list margins:\n")
    add(_tbl(lv, ["lines", "profit_margin", "loss_line_share", "profit_per_line"],
             {"lines": "int", "profit_margin": "pct", "loss_line_share": "pct", "profit_per_line": "money"}))
    add(f"\n{TAG['C']} Correlations between discount and margin at different levels of aggregation:\n")
    add(_tbl(r["correlations"][r["correlations"]["relationship"].str.contains("margin")],
             ["relationship", "level", "n", "spearman_rho", "strength"], {"n": "int", "spearman_rho": "num"}, index=False))
    add(f"\n{TAG['E']} **Verified mechanism.** If unit cost is fixed and a discount only lowers the price, a product with list margin m0 sold at discount d "
        "must earn margin 1 - (1 - m0) / (1 - d). Tested on the data:\n")
    add(f"- The list margin implied by each line is constant within every product (largest spread across {ic['products']:,} products: {ic['max_spread_implied_list_margin']:.1e}).")
    add(f"- For {ic['discounted_lines_tested']:,} discounted lines of products also sold at full price, the predicted margin matches the actual margin "
        f"(largest error {ic['max_abs_prediction_error']:.1e}, i.e. exact).")
    add("- Consequently a line loses money exactly when its discount exceeds its product's list margin. (On its own, that line-level "
        "equivalence is an algebraic identity; the evidence is the two tests above, which show the list margin is a fixed property of each product.)\n")
    add(f"![identity]({figs['D4']})\n")
    add("This also confirms assumption A1 (sales are recorded net of discount) and shows that, in this dataset, profit is generated by a fixed cost "
        "per product. That exactness is typical of synthetic data; real cost data would be noisier.\n")

    # ---------------- 9. Evidence ladder ----------------
    add("## 9. What can and cannot be concluded")
    add("| Claim | Type | Evidence | Status |")
    add("|---|---|---|---|")
    add(f"| Deep discounts coincide with losses | Descriptive | Every band above 20% loses money; beyond-break-even revenue loses {money(-hb['profit'])} | Established |")
    add(f"| Higher discount goes with lower margin | Correlation | rho {corr.loc[('Discount vs line margin','Order line'),'spearman_rho']:.2f} (lines), "
        f"{corr.loc[('Effective discount vs margin','State (30+ orders)'),'spearman_rho']:.2f} (states) | Established |")
    add("| Discount lowers the margin of the unit it is applied to, by a known amount | Explanation (price arithmetic) | Exact fit of 1 - (1-m0)/(1-d) | "
        "Established for unit economics, given fixed unit cost |")
    add(f"| Discounts are associated with more volume or growth | Correlation | rho near 0 on units, basket share and state growth | Not supported |")
    add("| Removing deep discounts would raise total profit | Causal | Requires knowing how volume responds; no variation within rules or over time | **Cannot be concluded** |")
    add("| Discounting caused the 2026 margin decline | Causal | Four yearly observations; mix also changed | **Cannot be concluded** |\n")
    add("**Why the causal question stays open.** To estimate what a discount *does* to total profit, we would need comparable sales with and without it: "
        f"the same rule at different times, or different discounts within one rule. Neither exists: {rs['cells_with_more_than_one_discount_level']} of "
        f"{rs['policy_cells']} rules have more than one discount level, and {rs['multi_year_cells_where_rule_changed']} of "
        f"{rs['cells_observed_in_several_years']} rules seen in several years ever changed.\n")

    # ---------------- 10. Management ----------------
    add("## 10. Management interpretation")
    add("**Is discounting helping the business generate profitable growth?** On the evidence available, discounting as currently applied is not visibly doing so:\n")
    add(f"1. **Moderate discounts look sustainable; deep ones do not.** Discounts well within list margin remain profitable "
        f"({money(safe['profit'])}). Discounts beyond break-even ({pct(hb['share_of_sales'])} of revenue) lose money on every such unit, by construction.")
    add(f"2. **No visible volume payoff.** Discounted lines do not carry larger baskets, heavily discounted sub-categories do not take a larger share of "
        f"a state's purchases, and high-discount states have not grown faster. {growth_sentence(gsum)}")
    add("3. **The problem is concentrated and rule-based.** Losses come from specific state x sub-category rules (Phase 5), so the fix is a policy decision, not a "
        "broad price cut or customer action.")
    add(f"4. **Discount should be set relative to list margin.** A single company-wide cap ignores that Tables break even at about "
        f"{pct(sub.loc['Tables','list_margin'],0)} while Binders break even near {pct(sub.loc['Binders','list_margin'],0)}.\n")
    add("**Recommended actions (in order)**")
    add("1. Introduce a guardrail: no discount above the product's list margin without explicit approval.")
    add("2. Review the rules that sell beyond break-even, starting with the largest losses (Phase 5 priority list).")
    add("3. Run a controlled pilot: lower the deepest rules in a few states, keep comparable states unchanged, and measure orders, units and profit for at least two quarters.")
    add("4. Report effective discount and beyond-break-even revenue share as standing KPIs in the dashboard.\n")
    add("## 11. Limitations")
    add("- **Synthetic, mechanically generated profit.** The exact price-arithmetic fit shows profit is computed from a fixed unit cost; real businesses have volume discounts, rebates and variable costs.")
    add("- **No counterfactual.** No variation in discount within rules or over time; associations with volume cannot be read as effects.")
    add("- **No cost, competitor or promotion data.** We cannot see why rules were set, or whether discounts matched competitor prices.")
    add("- **Returns not netted.** Returns are recorded per order only and are not deducted from profit.")
    add("- **Dataset years are synthetic.**\n")
    add("## 12. Validation")
    add(md_table(validation, floatfmt=lambda v: f"{v:,.4f}"))
    return "\n".join(L)
