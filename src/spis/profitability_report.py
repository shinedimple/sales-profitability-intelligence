"""Builds the Phase 5 profitability report. All numbers are read from computed results."""
from __future__ import annotations

import pandas as pd

from .findings import _tbl, money, pct
from .profitability import DEEP_DISCOUNT, MIN_LINES, QUADRANTS
from .reporting import md_table

EX_COLS = ["product_label", "sub_category", "sales", "profit", "profit_margin", "effective_discount",
           "lines", "full_price_margin", "discounted_margin"]
EX_FMT = {"sales": "money", "profit": "money", "profit_margin": "pct", "effective_discount": "pct",
          "lines": "int", "full_price_margin": "pct", "discounted_margin": "pct"}

QUADRANT_TEXT = {
    "Q1": dict(
        meaning=("These products carry the business: large revenue at margins above the company hurdle. They are the profit base to protect. "
                 "Their lower effective discount suggests they are mostly sold at or near list price."),
        limitations=("Membership depends on thresholds (tested below). A product can be Q1 overall while still having loss-making discounted lines; "
                     "its full-price vs discounted margins are shown for that reason."),
        action="Protect: keep discount eligibility tight and monitor stock availability and price changes."),
    "Q2": dict(
        meaning=("These products generate revenue comparable to the core earners, but as a group they lose money. They are where revenue "
                 "is earned without profit. Their effective discount is roughly double that of Q1, and their own full-price lines are profitable "
                 "(see the examples), which points to discounting rather than the products themselves."),
        limitations=("Association, not cause: deep discounts happen in particular states (discount is fixed by state x sub-category), so product, "
                     "location and discount are intertwined. Low margins may also reflect cost or freight, which the data does not contain."),
        action="Fix first: review the discount rules applied to these products, starting with the largest absolute losses."),
    "Q3": dict(
        meaning=("Many small, high-margin items (paper, art, labels, envelopes). They are efficient but small in revenue terms, "
                 "so growing them is a much smaller lever than repairing the loss-making discount rules (section 8)."),
        limitations="Low revenue per product means few transactions; margins are reliable as a group, less so per product.",
        action="Maintain: useful for basket building and margin mix; not a primary lever for the profit problem."),
    "Q4": dict(
        meaning=("Small revenue and negative margin, with the highest effective discount of any quadrant. They add complexity "
                 "and losses without meaningful revenue."),
        limitations="Very small sample per product; some may be clearance items or one-off promotions that the data cannot identify.",
        action="Review: candidates for removing discount eligibility or rationalising the range, after checking their role in larger orders."),
}


def build_report(r: dict, figs: dict[str, str], validation: pd.DataFrame) -> str:
    o, cm, qs, p = r["overall"], r["company_margin"], r["quadrants"], r["products"]
    L: list[str] = []
    add = L.append

    add("# Phase 5 — Profitability Analysis: Where Is Profit Made and Where Is It Destroyed?")
    add("**Project:** Sales & Profitability Intelligence System  ")
    add(f"**Scope:** core scope (US, suspected copies excluded). Revenue {money(o['sales'])}, profit {money(o['profit'])}, "
        f"margin {pct(cm)}, {len(p):,} products, {int(o['lines']):,} order lines.  ")
    add(f"**Validation:** {(validation.status == 'PASS').sum()}/{len(validation)} checks passed (totals reconcile to the SQL layer).  ")
    add("_Generated by `scripts/run_phase5_profitability.py`; all figures are computed at run time._\n")

    # ------------------------------------------------------------------
    add("## 1. Executive summary")
    q1, q2 = qs.loc["Q1"], qs.loc["Q2"]
    rb, ld = r["rule_bands"], r["loss_diagnosis"]
    deep = rb.loc[rb.index.isin(["41-60%", "61-80%"])]
    add(f"- **Profit is made by a quarter of the products.** Q1 core earners are {pct(q1['share_of_products'],0)} of products, "
        f"{pct(q1['share_of_sales'],0)} of revenue and {pct(q1['share_of_profit'],0)} of profit (margin {pct(q1['profit_margin'])}).")
    add(f"- **Almost as much revenue earns nothing.** Q2 margin leaks carry {pct(q2['share_of_sales'],0)} of revenue but lose "
        f"{money(-q2['profit'])} as a group, at an effective discount of {pct(q2['effective_discount'])} (Q1: {pct(q1['effective_discount'])}).")
    add(f"- **No product loses money at full price.** Every loss-making line in the data is a discounted line. Of the "
        f"{int(ld['products'].sum())} loss-making products, {int(ld.loc['Profitable at full price, loss when discounted','products'])} are profitable "
        f"on their own full-price sales; the other {int(ld.loc['Only ever sold discounted (cannot test)','products'])} were never sold at full price.")
    add(f"- **Discount is the dimension that best separates profitable from unprofitable sales.** Discount level accounts for "
        f"{pct(r['driver'].set_index('dimension').loc['Discount level','eta_squared'],0)} of line-margin variation; region and segment for less than 1%.")
    add(f"- **Losses sit in a small number of discount rules.** The {int(deep['cells'].sum())} state x sub-category rules above 40% are all loss-making "
        f"and together lose {money(-deep['profit'].sum())} on {money(deep['sales'].sum())} revenue.")
    add("- **None of this proves cause.** Discount is fixed by state and sub-category, so discount, location and product cannot be fully separated. "
        "The evidence identifies where to investigate, not what will happen if rules change.\n")

    # ------------------------------------------------------------------
    add("## 2. Analytical framework")
    add("| Element | Definition | Why |")
    add("|---|---|---|")
    add(f"| Unit | Product (`product_key`), plus the policy cell (state x sub-category) | Products are what management prices; the policy cell is where discount is decided |")
    add(f"| Evidence rule | A product needs at least {MIN_LINES} order lines to be classified | Prevents single-sale products from being labelled leaders or losers |")
    add(f"| Sales axis | Revenue >= median of eligible products ({money(r['sales_cut'])}) = high | Median is robust to the long tail of very large products |")
    add(f"| Profit axis | Margin >= company margin ({pct(cm)}) = high | The hurdle every product must clear to avoid diluting overall margin |")
    add(f"| Deep discount | Effective discount >= {pct(DEEP_DISCOUNT,0)} | Phase 4: at 30%+ almost all lines lose money |")
    add("| Ranking metric | Always stated: absolute profit (impact), margin (efficiency) or loss amount (damage) | Avoids unexplained 'best' or 'worst' labels |")
    add("\n**Quadrants**\n")
    for k, v in QUADRANTS.items():
        add(f"- **{k}** — {v}")
    add("")

    # ------------------------------------------------------------------
    add("## 3. Quadrant results")
    add(f"![quadrants]({figs['P1']})\n")
    add(_tbl(qs, ["products", "share_of_products", "sales", "share_of_sales", "profit", "share_of_profit",
                  "profit_margin", "effective_discount", "loss_products", "avg_quantity_per_line"],
             {"products": "int", "share_of_products": "pct", "sales": "money", "share_of_sales": "pct", "profit": "money",
              "share_of_profit": "pct", "profit_margin": "pct", "effective_discount": "pct", "loss_products": "int",
              "avg_quantity_per_line": "num"}))
    add(f"\n![shares]({figs['P2']})\n")
    add(f"![waterfall]({figs['P3']})\n")
    comp = r["composition"]
    for q in ["Q1", "Q2", "Q3", "Q4"]:
        row, txt = qs.loc[q], QUADRANT_TEXT[q]
        top_subs = comp[q].sort_values(ascending=False).head(3)
        add(f"### {q} — {QUADRANTS[q]}")
        add(f"**Metrics.** {int(row['products'])} products, revenue {money(row['sales'])} ({pct(row['share_of_sales'])}), "
            f"profit {money(row['profit'])} ({pct(row['share_of_profit'])}), margin {pct(row['profit_margin'])}, "
            f"effective discount {pct(row['effective_discount'])}, {int(row['loss_products'])} loss-making products. "
            f"Largest sub-categories by revenue share: " + ", ".join(f"{s} {pct(v,0)}" for s, v in top_subs.items()) + ".\n")
        add("**Examples** (selected by largest absolute profit impact, i.e. |profit|):\n")
        add(_tbl(r["examples"][q], EX_COLS, EX_FMT, index=False))
        add(f"\n**Business meaning.** {txt['meaning']}\n")
        add(f"**Limitations.** {txt['limitations']}\n")
        add(f"**Implication for management.** {txt['action']}\n")
    na = qs.loc["NA"]
    add(f"### Insufficient evidence (< {MIN_LINES} lines)")
    add(f"{int(na['products'])} products ({pct(na['share_of_sales'])} of revenue) are not classified. "
        f"Machines make up {pct(comp.loc['Machines','NA'],0)} of this group's revenue: high-value items sold only once or twice, "
        "whose margins depend on single transactions. They are reviewed transaction by transaction in section 5.\n")

    add("### Robustness: do the quadrants survive different thresholds?")
    add(_tbl(r["sensitivity"], ["scenario", "products_reclassified", "share_reclassified", "q2_products", "q2_sales", "q2_profit"],
             {"products_reclassified": "int", "share_reclassified": "pct", "q2_products": "int", "q2_sales": "money", "q2_profit": "money"}, index=False))
    s = r["sensitivity"]
    add(f"\nMoving the sales threshold by 10 percentiles reclassifies about {pct(s.iloc[1]['share_reclassified'],0)} of products, "
        f"but the margin-leak quadrant keeps losing money in every scenario ({money(s['q2_profit'].max())} to {money(s['q2_profit'].min())}). "
        "The conclusion does not depend on the exact cut-off.\n")

    # ------------------------------------------------------------------
    neg, pp = r["negative"], r["pareto"]
    add("## 4. Products with negative profit")
    add(f"**Metrics.** {pp['loss_products']} products lose money, {money(-neg['profit'].sum())} in total "
        f"({int(neg['eligible'].sum())} of them have {MIN_LINES}+ lines). Ranked by loss amount: the top {pp['products_for_50pct_of_losses']} "
        f"account for 50% of product losses and the top {pp['products_for_80pct_of_losses']} for 80%.\n")
    add(f"![pareto]({figs['P4']})\n")
    by_sub = neg.groupby("sub_category").agg(products=("product_key", "size"), loss=("profit", "sum")).sort_values("loss").head(6)
    by_sub["share_of_product_losses"] = by_sub["loss"] / neg["profit"].sum()
    add(_tbl(by_sub, ["products", "loss", "share_of_product_losses"], {"products": "int", "loss": "money", "share_of_product_losses": "pct"}))
    add("\n**What each loss-making product's own history shows** (diagnosis based on its full-price vs discounted lines):\n")
    add(_tbl(ld, ["products", "loss", "share_of_loss", "sales", "median_discount"],
             {"products": "int", "loss": "money", "share_of_loss": "pct", "sales": "money", "median_discount": "pct"}))
    add("\n**Examples** (ranked by loss amount):\n")
    add(_tbl(neg.head(10), EX_COLS, EX_FMT, index=False))
    add("\n**Business meaning.** Losses are concentrated in a few dozen products, mostly Machines and Tables, "
        "and in this dataset they arise only on discounted lines. There is no product that is unprofitable at list price.\n")
    add("**Limitations.** Product totals for high-value items rest on very few transactions. 'Profitable at full price' is measured on that product's "
        "own full-price lines, which may have been sold in different states or years than its discounted lines.\n")

    # ------------------------------------------------------------------
    hd = r["high_discount"]
    lens = hd.groupby("high_discount_lens").agg(products=("product_key", "size"), sales=("sales", "sum"),
                                                profit=("profit", "sum"), median_margin=("profit_margin", "median"),
                                                median_discount=("effective_discount", "median"))
    add("## 5. Products with unusually high discount")
    add("Two stated lenses are used, because 'unusually high' can mean high in absolute terms or high for the product's sub-category:\n")
    add(f"- **Absolute:** effective discount >= {pct(DEEP_DISCOUNT,0)}.")
    add("- **Relative:** effective discount above the 90th percentile of eligible products in the same sub-category.\n")
    add(_tbl(lens, ["products", "sales", "profit", "median_margin", "median_discount"],
             {"products": "int", "sales": "money", "profit": "money", "median_margin": "pct", "median_discount": "pct"}))
    add("\n**Examples flagged by both lenses** (ranked by loss amount):\n")
    add(_tbl(hd[hd["high_discount_lens"] == "Both"].sort_values("profit").head(8), EX_COLS, EX_FMT, index=False))
    add("\n**Business meaning.** Products flagged by both lenses are where discounting is extreme in every sense, and they lose money as a group. "
        "Products flagged only on the absolute lens can stay profitable overall because their full-price sales subsidise the discounted ones.\n")
    add("**Limitations.** A product's effective discount reflects where it was sold (state rules), not a product-specific decision.\n")

    # ------------------------------------------------------------------
    dd = r["within_product"]
    dg = dd.groupby("diagnosis").agg(products=("product_key", "size"), profit=("profit", "sum"),
                                     median_full_price_margin=("full_price_margin", "median"),
                                     median_discounted_margin=("discounted_margin", "median"),
                                     median_gap=("margin_gap_pp", "median"))
    add("## 6. Where discounts appear associated with weak profitability")
    add("**Method: compare each product with itself.** For every product sold both at full price and at a discount, its margin on full-price lines "
        "is compared with its margin on discounted lines. This holds the product constant, which comparisons across products cannot do.\n")
    add(f"**Metrics.** {len(dd):,} products qualify. In {pct((dd['discounted_margin'] < dd['full_price_margin']).mean(),0)} of them the discounted margin is lower. "
        f"The median gap is {dd['margin_gap_pp'].median()*100:+.1f} percentage points.\n")
    add(_tbl(dg, ["products", "profit", "median_full_price_margin", "median_discounted_margin", "median_gap"],
             {"products": "int", "profit": "money", "median_full_price_margin": "pct", "median_discounted_margin": "pct", "median_gap": "pct"}))
    add(f"\n![dumbbell]({figs['P5']})\n")
    add(f"**Business meaning.** For {int(dg.loc['Profitable at full price, loss when discounted','products'])} products, the full-price business is profitable "
        "and the discounted business loses money. These are the clearest candidates for tighter discount limits.\n")
    add("**Limitations.** The full-price and discounted lines of a product were sold in different states (because discount is set by state), "
        "so the gap mixes the discount with any state differences. This is a strong association, not a causal estimate.\n")

    # ------------------------------------------------------------------
    dm = r["driver"]
    add("## 7. How the dimensions relate to profitability")
    add("**Method.** For each dimension, the sales-weighted share of line-margin variation that lies *between* its groups (eta-squared). "
        "1.0 means the groups fully separate high- and low-margin sales; 0 means the dimension tells us nothing about margin. "
        "This is descriptive, and dimensions with more groups score higher mechanically.\n")
    add(f"![drivers]({figs['P6']})\n")
    add(_tbl(dm, ["dimension", "groups", "eta_squared"], {"groups": "int", "eta_squared": "pct"}, index=False))
    dmi = dm.set_index("dimension")["eta_squared"]
    add(f"\n**Reading.** Discount level ({pct(dmi['Discount level'],0)}, only 12 groups) separates margins far better than product "
        f"({pct(dmi['Product'],0)}, 1,894 groups): the same product earns very different margins at different discounts. "
        f"State x sub-category, the unit at which discount is set, accounts for {pct(dmi['State x sub-category (policy cell)'],0)}. "
        f"Region ({pct(dmi['Region'],1)}), segment ({pct(dmi['Segment'],1)}) and quantity ({pct(dmi['Quantity band'],1)}) add almost nothing.\n")
    add("**Supporting tables**\n")
    for name, title in [("dim_category", "Category"), ("dim_segment", "Customer segment"), ("dim_region", "Region"),
                        ("dim_quantity", "Quantity per line")]:
        t = r[name]
        add(f"*{title}*\n")
        add(_tbl(t, [c for c in ["sales", "profit", "profit_margin", "effective_discount", "share_of_sales", "share_of_profit"] if c in t.columns],
                 {"sales": "money", "profit": "money", "profit_margin": "pct", "effective_discount": "pct",
                  "share_of_sales": "pct", "share_of_profit": "pct"}))
        add("")
    add("**Limitations.** Eta-squared measures separation, not influence. The dataset appears to generate profit largely from discount, which would inflate the discount score.\n")

    # ------------------------------------------------------------------
    cells = r["cells"]
    add("## 8. Policy cells: where exactly is profit destroyed?")
    add(f"Discount is fixed per state x sub-category, so each of the {len(cells)} combinations behaves like one pricing rule. "
        f"{int(cells['profit_destroying'].sum())} rules are loss-making and together lose {money(-cells.loc[cells['profit_destroying'],'profit'].sum())}, "
        f"which is {pct(cells.loc[cells['profit_destroying'],'profit'].sum() / r['line_losses'],0)} of all line-level losses.\n")
    add(f"![rule bands]({figs['P8']})\n")
    add(_tbl(rb, ["cells", "loss_cells", "share_cells_loss_making", "sales", "profit", "profit_margin"],
             {"cells": "int", "loss_cells": "int", "share_cells_loss_making": "pct", "sales": "money", "profit": "money", "profit_margin": "pct"}))
    add(f"\n![heatmap]({figs['P7']})\n")
    add("**The 15 most loss-making rules** (ranked by profit, most negative first):\n")
    add(_tbl(cells.head(15), ["state_province", "sub_category", "discount_rule", "sales", "profit", "profit_margin", "lines"],
             {"discount_rule": "pct", "sales": "money", "profit": "money", "profit_margin": "pct", "lines": "int"}, index=False))
    add("\n**Limitations.** Some rules rest on few lines (e.g. Machines), so their losses come from a handful of orders. "
        "Whether the rule pattern exists in the real business must be confirmed against the actual pricing policy.\n")

    # ------------------------------------------------------------------
    add("## 9. What should management investigate first?")
    add("**Ranking metric:** profit destroyed (sum of negative profit) in the unit, read together with the number of order lines behind it "
        "(evidence strength). 'Loss at stake' is the size of the current loss, **not** a forecast of profit gained by changing the rule: "
        "volumes might fall if discounts are reduced, and that cannot be measured from this data.\n")
    add(md_table(r["priorities"], floatfmt=lambda v: f"{v:,.0f}"))
    add("\n**Suggested sequence**")
    add("1. **Confirm the discount rule table** with the commercial team: who sets discounts by state and sub-category, and why some states never sell at full price.")
    add("2. **Review the rules above 40%** (priority 1): every one loses money. Ask what each was intended to achieve.")
    pr_ = r["priorities"].set_index("priority")
    add(f"3. **Review 21-40% rules** (priority 2), starting with the largest losses ({pr_.loc[2, 'main_sub_categories']}).")
    add(f"4. **Check the 1-20% rules that still lose money** (priority 3): these point to thin list-price margins "
        f"({pr_.loc[3, 'main_sub_categories']}) rather than discounting alone.")
    add("5. **Audit the few high-value Machines transactions** (priority 4): large losses from very few orders; check whether they were approved exceptions.")
    add("6. **Before changing any rule, run a controlled pilot** in a few states and measure order volume as well as margin.\n")
    add("## 10. What this analysis does not show")
    add("- That lowering discounts would increase profit: volume effects are unknown, and there is no comparison group.")
    add("- Why Furniture list-price margins are thin: there is no cost or freight data.")
    add("- Product profitability net of returns: returns are recorded per order only.\n")
    add("## 11. Validation")
    add(md_table(validation, floatfmt=lambda v: f"{v:,.2f}"))
    return "\n".join(L)
