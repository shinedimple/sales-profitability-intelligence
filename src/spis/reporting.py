"""Builds the human-readable Phase 1 data-quality report (Markdown)."""
from __future__ import annotations

from datetime import date

import pandas as pd

from . import config
from .issue_catalog import ISSUE_CATALOG

PROCESSED_COLUMN_NOTES = {
    "postal_code": "Text. US codes zero-padded to 5 digits; Canadian codes are 3-character FSA.",
    "customer_id": "Upper-cased (DQ03).",
    "customer_name": "Lower-case word starts capitalised (DQ04).",
    "dq_is_identity_anomaly": "DQ05: name with several IDs, or order with several customers.",
    "dq_is_placeholder_customer": "DQ06: test-like customer name.",
    "dq_is_value_copy_suspect": "DQ08: identical financials on different products in one order.",
    "dq_is_price_anomaly": "DQ09: implied list price >50% from product median.",
    "dq_is_clone_copy": "DQ18: non-US line copied from another order (US twin or CA-CA).",
    "dq_is_sales_outlier": "DQ10: sales beyond 3 x IQR fence.",
    "dq_is_profit_outlier": "DQ10: profit beyond 3 x IQR fence.",
    "exclude_from_customer_analysis": "True if DQ05 or DQ06. Use in customer-level analysis only.",
}


def md_table(df: pd.DataFrame, index: bool = False, floatfmt: str = "{:,.2f}") -> str:
    """Dependency-free Markdown table renderer."""
    if index:
        df = df.reset_index()
    def fmt(v):
        if isinstance(v, float):
            if pd.isna(v):
                return ""
            return floatfmt(v) if callable(floatfmt) else floatfmt.format(v)
        return str(v).replace("|", "\\|").replace("\n", " ")
    header = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, sep, *body])


def build_report(profile: dict, checks: pd.DataFrame, issue_log: pd.DataFrame,
                 cleaning_log: pd.DataFrame, validation: pd.DataFrame,
                 clean_orders: pd.DataFrame, raw_hash: str, run_date: date) -> str:
    L: list[str] = []
    add = L.append

    add("# Phase 1 — Data Quality Audit Report")
    add("**Project:** Sales & Profitability Intelligence System  ")
    add(f"**Run date:** {run_date}  ")
    add(f"**Raw source:** `data/raw/{config.RAW_FILE.name}` (SHA-256 `{raw_hash[:16]}…`)  ")
    add("**Pipeline:** RAW → AUDIT → CLEANING → VALIDATION → PROCESSED  ")
    add("_This report is generated by `scripts/run_phase1_data_quality.py`. Do not edit by hand._\n")

    # ---- Summary
    status_counts = checks["status"].value_counts().to_dict()
    found = checks.loc[checks["issue_code"].ne("") & checks["status"].ne("PASS"), "issue_code"].unique()
    add("## 1. Executive summary")
    add(f"- Audit checks run: **{len(checks)}** — " +
        ", ".join(f"{k}: {v}" for k, v in sorted(status_counts.items())))
    add(f"- Distinct issues identified: **{len(found)}** "
        f"(corrected: {sum(ISSUE_CATALOG[c]['decision'] == 'CORRECT' for c in found)}, "
        f"flagged: {sum(ISSUE_CATALOG[c]['decision'] == 'FLAG' for c in found)}, "
        f"documented: {sum(ISSUE_CATALOG[c]['decision'] == 'DOCUMENT' for c in found)})")
    add(f"- Validation checks: **{(validation['status'] == 'PASS').sum()} / {len(validation)} passed**")
    add(f"- Processed orders: **{len(clean_orders):,} rows** "
        f"(raw {profile['dimensions']['orders'][0]:,})\n")

    # ---- Profile
    add("## 2. Dataset profile (raw)")
    dims = pd.DataFrame([(k, v[0], v[1]) for k, v in profile["dimensions"].items()],
                        columns=["table", "rows", "columns"])
    add(md_table(dims) + "\n")
    add("### Columns and data types (Orders)")
    dt = pd.DataFrame({"column": list(profile["dtypes"].keys()),
                       "dtype": list(profile["dtypes"].values()),
                       "nulls": [profile["missing_by_column"][c] for c in profile["dtypes"]]})
    add(md_table(dt) + "\n")
    add(f"Postal Code mixed Python types: `{profile['postal_code_types']}`\n")
    dr = profile["date_range"]
    add("### Date range")
    add(f"- Order date: {dr['order_date'][0]} → {dr['order_date'][1]}")
    add(f"- Ship date: {dr['ship_date'][0]} → {dr['ship_date'][1]}")
    add(f"- Rows per year: {profile['rows_per_year']}\n")
    add("Shipping days by ship mode:\n")
    add(md_table(profile["ship_days_by_mode"], index=True) + "\n")
    add("### Unique counts")
    add(md_table(pd.DataFrame(list(profile["unique_counts"].items()), columns=["field", "unique"])) + "\n")
    add("### Categorical values")
    for col, counts in profile["categorical_counts"].items():
        add(f"- **{col}**: " + ", ".join(f"{k} ({v:,})" for k, v in counts.items()))
    add("\n**Category → sub-categories**")
    for cat, subs in profile["category_tree"].items():
        add(f"- {cat}: {', '.join(subs)}")
    add("\n### Numerical distributions")
    add(md_table(profile["numeric_summary"], index=True) + "\n")
    add(f"Discount levels (rows): {profile['discount_levels']}\n")
    add("### Outlier fences (IQR method)")
    add(md_table(profile["outliers"], index=True) + "\n")

    # ---- Checks
    add("## 3. Audit check results")
    add(md_table(checks[["section", "check", "status", "n_affected", "issue_code", "detail"]]) + "\n")

    # ---- Issues
    add("## 4. Issues, interpretation and decisions")
    counts = issue_log["issue_code"].value_counts().to_dict()
    for code in sorted(found):
        meta = ISSUE_CATALOG[code]
        evidence = checks.loc[checks["issue_code"] == code, "detail"].iloc[0]
        add(f"### {code} — {meta['title']}")
        add(f"- **Severity:** {meta['severity']} | **Decision:** {meta['decision']} | "
            f"**Rows in issue log:** {counts.get(code, 'n/a (dataset-level)')}")
        add(f"- **Evidence:** {evidence}")
        add(f"- **What it means:** {meta['meaning']}")
        add(f"- **Why this decision:** {meta['why']}")
        add(f"- **Approach:** {meta['approach']}\n")

    # ---- Cleaning
    add("## 5. Cleaning log")
    add(md_table(cleaning_log) + "\n")

    # ---- Validation
    add("## 6. Validation results")
    add(md_table(validation) + "\n")

    # ---- Outputs
    add("## 7. Processed outputs")
    add(f"- `data/processed/{config.OUT_ORDERS.name}` — clean order lines (grain: one product line per order)")
    add(f"- `data/processed/{config.OUT_RETURNS.name}` — returned orders (`order_id`, `is_returned`)")
    add(f"- `data/processed/{config.OUT_PEOPLE.name}` — region → regional manager")
    add("- `reports/phase1/audit_checks.csv`, `dq_issue_log.csv`, `cleaning_log.csv`, "
        "`removed_rows.csv`, `validation_results.csv`\n")
    add("**Processed orders schema**\n")
    schema = pd.DataFrame({"column": clean_orders.columns,
                           "dtype": clean_orders.dtypes.astype(str).values,
                           "note": [PROCESSED_COLUMN_NOTES.get(c, "") for c in clean_orders.columns]})
    add(md_table(schema) + "\n")
    add("> Load processed data with `spis.io_utils.read_orders_clean()` so that `postal_code` "
        "stays text.\n")

    add("## 8. Assumptions carried forward")
    add("- A1: `sales` is net of discount.\n- A2: Canadian values use the same currency as US values.\n"
        "- A3: `profit` is not adjusted for returns.\n- A4: Implied list price = sales / "
        "(quantity × (1 − discount)).\n- A5: Dataset years are synthetic and are referred to as "
        "'dataset years'.\n- A6: Where a Canadian line duplicates a US line, the US line is the "
        "original and the Canadian line is the copy.")
    return "\n".join(L)
